"""Regenerate testdata/vectors.json from the Python encoder. Deterministic: fixed master, clock and nonces.

    uv run python scripts/make_vectors.py          # rewrite the file
    uv run python scripts/make_vectors.py --check  # exit 1 if the committed file differs
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from tailisman._token import Claim, b64encode, derive_consumer_key, encode, format_key, sign

OUT = Path(__file__).resolve().parent.parent / "testdata" / "vectors.json"
MASTER = bytes(range(32))
NOW = 1760000030
HECKLE = "https://heckle.example.com"
NOTES = "https://notes.example.com"


def nonce(n: int) -> str:
    return b64encode(bytes([n]) * 16)


def claim(**overrides) -> Claim:
    fields = dict(
        node_id="nEXAMPLE1CNTRL",
        node_name="laptop",
        login="owner@example.com",
        audience=HECKLE,
        issued_at=NOW - 10,
        expires_at=NOW + 50,
        nonce=nonce(1),
    )
    return Claim(**{**fields, **overrides})


def payload(c: Claim) -> dict:
    return {"nid": c.node_id, "nn": c.node_name, "sub": c.login, "aud": c.audience, "iat": c.issued_at, "exp": c.expires_at, "nonce": c.nonce}


def signed(fields: dict, key: bytes) -> str:
    return sign(json.dumps(fields, separators=(",", ":")), key)


def ok(c: Claim) -> dict:
    return {"ok": True, "claim": {k: getattr(c, k) for k in ("node_id", "node_name", "login", "audience", "issued_at", "expires_at", "nonce")}}


def build() -> dict:
    key = {origin: derive_consumer_key(MASTER, origin) for origin in (HECKLE, NOTES)}
    heckle = key[HECKLE]
    valid = claim()
    valid_token = encode(valid, heckle)
    head, body, mac = valid_token.split(".")
    flipped = mac[:-2] + ("A" if mac[-2] != "A" else "B") + mac[-1]
    missing = payload(claim(nonce=nonce(5)))
    del missing["nonce"]
    extra = {**payload(claim(nonce=nonce(6))), "admin": True}
    float_iat = json.dumps(payload(claim(nonce=nonce(7))), separators=(",", ":")).replace(f'"iat":{NOW - 10}', f'"iat":{NOW - 10}.0')

    cases = [
        ("valid", HECKLE, valid_token, ok(valid)),
        ("valid at the edge of leeway after exp", HECKLE, encode(claim(expires_at=NOW - 5, issued_at=NOW - 65, nonce=nonce(8)), heckle), ok(claim(expires_at=NOW - 5, issued_at=NOW - 65, nonce=nonce(8)))),
        ("bad mac", HECKLE, f"{head}.{body}.{flipped}", {"code": "bad_signature"}),
        ("token for another audience under that audience's key", NOTES, valid_token, {"code": "bad_signature"}),
        ("aud mismatch under the same key", HECKLE, encode(claim(audience="https://evil.example.com", nonce=nonce(2)), heckle), {"code": "wrong_audience"}),
        ("expired", HECKLE, encode(claim(issued_at=NOW - 80, expires_at=NOW - 20, nonce=nonce(3)), heckle), {"code": "expired"}),
        ("not yet valid", HECKLE, encode(claim(issued_at=NOW + 30, expires_at=NOW + 90, nonce=nonce(4)), heckle), {"code": "not_yet_valid"}),
        ("missing key", HECKLE, signed(missing, heckle), {"code": "malformed"}),
        ("extra key", HECKLE, signed(extra, heckle), {"code": "malformed"}),
        ("iat is a float", HECKLE, sign(float_iat, heckle), {"code": "malformed"}),
        ("iat is a string", HECKLE, signed({**payload(claim(nonce=nonce(9))), "iat": str(NOW)}, heckle), {"code": "malformed"}),
        ("nonce is not 16 bytes", HECKLE, signed({**payload(claim()), "nonce": "short"}, heckle), {"code": "malformed"}),
        ("key passed as token", HECKLE, format_key(heckle), {"code": "malformed"}),
        ("two parts", HECKLE, f"{head}.{body}", {"code": "malformed"}),
        ("padded base64", HECKLE, f"{head}.{body}.{mac}=", {"code": "malformed"}),
        ("empty", HECKLE, "", {"code": "malformed"}),
    ]
    return {
        "comment": "Generated by scripts/make_vectors.py. Do not edit by hand. Both test suites load this file and pass `now` as the clock with leeway 5.",
        "master": b64encode(MASTER),
        "now": NOW,
        "leeway": 5,
        "keys": {origin: format_key(k) for origin, k in key.items()},
        "origins": [
            {"input": "https://heckle.example.com", "expect": "https://heckle.example.com"},
            {"input": "HTTPS://Heckle.Example.COM", "expect": "https://heckle.example.com"},
            {"input": "https://heckle.example.com:443", "expect": "https://heckle.example.com"},
            {"input": "https://heckle.example.com/", "expect": "https://heckle.example.com"},
            {"input": "http://localhost:80", "expect": "http://localhost"},
            {"input": "http://localhost:8080", "expect": "http://localhost:8080"},
            {"input": "https://heckle.example.com:8443", "expect": "https://heckle.example.com:8443"},
            {"input": "https://heckle.example.com:08443", "expect": "https://heckle.example.com:8443"},
            {"input": "http://[::1]:8080", "expect": "http://[::1]:8080"},
            {"input": "https://heckle.example.com/path", "expect": None},
            {"input": "https://heckle.example.com?q=1", "expect": None},
            {"input": "https://user@heckle.example.com", "expect": None},
            {"input": "ftp://heckle.example.com", "expect": None},
            {"input": "heckle.example.com", "expect": None},
            {"input": "https://heckle.example.com:99999", "expect": None},
            {"input": "https://heckle.example.com:0", "expect": None},
            {"input": "", "expect": None},
            {"input": "https://heckle.example.\u212acom", "expect": None},
            {"input": "https://\u017fecret.example.com", "expect": None},
            {"input": "https://heckle.example.com\n", "expect": None},
        ],
        "cases": [{"name": name, "audience": aud, "key": format_key(key[aud]), "token": token, "expect": expect} for name, aud, token, expect in cases],
    }


def render() -> str:
    return json.dumps(build(), indent=2) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
